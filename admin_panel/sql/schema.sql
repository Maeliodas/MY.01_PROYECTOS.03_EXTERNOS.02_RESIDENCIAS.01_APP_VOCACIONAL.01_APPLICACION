CREATE TABLE catalog_meta (id TINYINT UNSIGNED PRIMARY KEY DEFAULT 1, version BIGINT UNSIGNED NOT NULL DEFAULT 1, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
